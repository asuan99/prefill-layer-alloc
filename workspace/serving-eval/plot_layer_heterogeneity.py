# SM-util priors when ncu data is unavailable (best-effort estimates for figure).
# These are illustrative; the real values come from ncu.
_SM_UTIL_PRIOR = {
    "ssm_scan":    45.0,  # SSM scan — memory-BW bound, low SM util
    "attn":        82.0,  # FlashAttention — compute intensive
    "gemm":        90.0,  # GEMM — near peak
    "elementwise": 30.0,  # elementwise — memory latency bound
    "other":       50.0,
}

_N_TIME_BINS = 500  # resolution of reconstructed SM-util trace


