def load_timeline(csv_path: Path) -> pd.DataFrame:
    """Load kernel timeline CSV from profile_layer_heterogeneity.py."""
    df = pd.read_csv(csv_path)
    required = {"kernel_name", "start_ns", "duration_ns", "layer_class"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Timeline CSV missing columns: {missing}")
    df["start_ns"]    = pd.to_numeric(df["start_ns"],    errors="coerce")
    df["duration_ns"] = pd.to_numeric(df["duration_ns"], errors="coerce")
    df = df.dropna(subset=["start_ns", "duration_ns"])
    df = df[df["duration_ns"] > 0]
    return df.reset_index(drop=True)


def load_ncu_sm_util(csv_path: Path) -> dict[str, float]:
    """Parse ncu CSV and return mean SM-util per kernel class.

    SM-util = sm__active_cycles_sum / sm__cycles_elapsed_sum × 100
    Returns {layer_class: mean_pct}.
    """
    try:
        raw = pd.read_csv(csv_path, comment="#")
    except Exception:
        return {}

    # ncu CSV headers vary by version; find the metric columns
    active_col  = next((c for c in raw.columns if "active_cycles_sum"  in c), None)
    elapsed_col = next((c for c in raw.columns if "cycles_elapsed_sum" in c), None)
    name_col    = next((c for c in raw.columns if c.strip().lower() == "kernel name"
                        or c.strip().lower() == "name"), None)

    if not (active_col and elapsed_col and name_col):
        return {}

    raw = raw.dropna(subset=[active_col, elapsed_col])
    raw["sm_util_pct"] = (
        pd.to_numeric(raw[active_col],  errors="coerce") /
        pd.to_numeric(raw[elapsed_col], errors="coerce").replace(0, np.nan)
    ) * 100

    # Classify each ncu kernel row
    from profile_layer_heterogeneity import classify_kernel
    raw["layer_class"] = raw[name_col].astype(str).apply(classify_kernel)

    util_by_class = (
        raw.groupby("layer_class")["sm_util_pct"]
        .mean()
        .dropna()
        .to_dict()
    )
    return util_by_class


# ---------------------------------------------------------------------------
# Reconstruction
# ---------------------------------------------------------------------------

def reconstruct_sm_util_trace(
    timeline: pd.DataFrame,
    ncu_util: dict[str, float],
    n_bins: int = _N_TIME_BINS,
) -> tuple[np.ndarray, np.ndarray]:
    """Build a time-binned SM-util trace from kernel timeline + ncu SM-util.

    Each time bin is weighted by the fraction of kernel time active in that bin
    and the SM-util assigned to the kernel's class.

    Args:
        timeline: DataFrame with start_ns, duration_ns, layer_class columns.
        ncu_util: {layer_class: sm_util_pct} from ncu.  Falls back to prior values.
        n_bins:   Number of time bins.

    Returns:
        (time_norm, sm_util_pct)  — both 1D arrays of length n_bins.
        time_norm: 0.0 → 1.0 (normalised pass duration)
        sm_util_pct: reconstructed SM-util per bin (0–100)
    """
    t_start = timeline["start_ns"].min()
    t_end   = (timeline["start_ns"] + timeline["duration_ns"]).max()
    t_range = t_end - t_start
    if t_range <= 0:
        return np.linspace(0, 1, n_bins), np.full(n_bins, np.nan)

    bins     = np.zeros(n_bins, dtype=np.float64)
    weights  = np.zeros(n_bins, dtype=np.float64)

    for _, row in timeline.iterrows():
        k_start = row["start_ns"] - t_start
        k_end   = k_start + row["duration_ns"]
        util    = ncu_util.get(row["layer_class"],
                               _SM_UTIL_PRIOR.get(row["layer_class"], 50.0))

        b0 = max(0, int(k_start / t_range * n_bins))
        b1 = min(n_bins, int(np.ceil(k_end / t_range * n_bins)))
        if b1 > b0:
            bins[b0:b1]    += util
            weights[b0:b1] += 1.0

    nonzero = weights > 0
    sm_util = np.full(n_bins, np.nan)
    sm_util[nonzero] = bins[nonzero] / weights[nonzero]
    # Forward-fill gaps (idle periods between kernels)
    for i in range(1, n_bins):
        if np.isnan(sm_util[i]):
            sm_util[i] = 0.0  # idle period → 0 % util

    return np.linspace(0, 1, n_bins), sm_util


def compute_zone_stats(
    timeline: pd.DataFrame,
    ncu_util: dict[str, float],
) -> dict[str, dict]:
    """Return {layer_class: {mean_sm_util, total_time_frac}} for annotation."""
    total_dur = timeline["duration_ns"].sum()
    stats: dict[str, dict] = {}
    for cls, grp in timeline.groupby("layer_class"):
        dur_frac = grp["duration_ns"].sum() / total_dur if total_dur > 0 else 0.0
        util     = ncu_util.get(cls, _SM_UTIL_PRIOR.get(cls, 50.0))
        stats[cls] = {"time_frac": dur_frac, "mean_sm_util": util}
    return stats


