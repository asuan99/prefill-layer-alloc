# Plotting
# ---------------------------------------------------------------------------

def _shade_zones(
    ax: plt.Axes,
    timeline: pd.DataFrame,
    t_range: float,
    alpha: float = 0.20,
) -> None:
    """Add vertical shaded regions per layer class (sorted by start time)."""
    t_start_ns = timeline["start_ns"].min()
    for _, row in timeline.iterrows():
        x0 = (row["start_ns"]                          - t_start_ns) / t_range
        x1 = (row["start_ns"] + row["duration_ns"]     - t_start_ns) / t_range
        color = _CLASS_COLORS.get(row["layer_class"], "#9E9E9E")
        ax.axvspan(x0, x1, alpha=alpha, color=color, linewidth=0)


def plot_sm_util_timeline(
    timeline: pd.DataFrame,
    ncu_util: dict[str, float],
    ax: plt.Axes,
    model_label: str,
    is_reconstructed: bool = True,
) -> None:
    """Plot the SM-util trace + zone shading on a given Axes."""
    t_norm, sm_util = reconstruct_sm_util_trace(timeline, ncu_util)
    zone_stats      = compute_zone_stats(timeline, ncu_util)

    t_range_ns = (timeline["start_ns"] + timeline["duration_ns"]).max() - timeline["start_ns"].min()
    _shade_zones(ax, timeline, t_range_ns, alpha=0.18)

    style = "--" if is_reconstructed else "-"
    lw    = 1.8 if is_reconstructed else 2.2
    ax.plot(t_norm, sm_util, style, color="#212121", linewidth=lw, zorder=5,
            label="Reconstructed SM-util" if is_reconstructed else "SM-util")

    # Smooth reference line
    from numpy.lib.stride_tricks import sliding_window_view
    win = min(40, len(sm_util) // 8)
    if win > 1:
        smooth = np.convolve(sm_util, np.ones(win) / win, mode="same")
        ax.plot(t_norm, smooth, "-", color="#F44336", linewidth=2.5, alpha=0.7, zorder=6,
                label="Smoothed (40-bin)")

    # Zone mean annotations
    t0_norm = 0.0
    for cls in ["ssm_scan", "attn", "gemm", "elementwise", "other"]:
        if cls not in zone_stats:
            continue
        s = zone_stats[cls]
        t_mid = t0_norm + s["time_frac"] / 2
        if s["time_frac"] > 0.05:  # only annotate zones > 5% of total time
            ax.text(
                t_mid, s["mean_sm_util"] + 3,
                f"{cls}\n{s['mean_sm_util']:.0f}%",
                ha="center", va="bottom", fontsize=7, color=_CLASS_COLORS.get(cls, "#000"),
                fontweight="bold", zorder=10,
            )
        t0_norm += s["time_frac"]

    suffix = " (reconstructed)" if is_reconstructed else ""
    ax.set_xlabel("Normalised pass time" + suffix, fontsize=10)
    ax.set_ylabel("SM utilisation (%)", fontsize=10)
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 110)
    ax.set_title(model_label, fontsize=11, fontweight="bold")
    ax.axhline(100, color="#9E9E9E", linestyle=":", linewidth=1, alpha=0.6)
    ax.grid(axis="y", alpha=0.25)

    # Legend patches for zone classes
    patches = [
        mpatches.Patch(color=_CLASS_COLORS[cls], alpha=0.6, label=_CLASS_LABELS[cls])
        for cls in _CLASS_LABELS if cls in zone_stats
    ]
    ax.legend(handles=patches + ax.get_lines(), loc="lower right", fontsize=7,
              ncol=2, framealpha=0.8)


def make_figure(
    hybrid_timeline: pd.DataFrame,
    hybrid_ncu:      dict[str, float],
    hybrid_label:    str,
    baseline_timeline: Optional[pd.DataFrame],
    baseline_ncu:      dict[str, float],
    baseline_label:    str,
    output_path: Path,
    seq_len: int,
    batch_size: int,
) -> None:
    n_panels = 2 if baseline_timeline is not None else 1
    fig, axes = plt.subplots(1, n_panels, figsize=(8 * n_panels, 5), squeeze=False)

    plot_sm_util_timeline(
        hybrid_timeline, hybrid_ncu, axes[0][0],
        model_label=f"{hybrid_label}  (hybrid SSM+Attn)",
        is_reconstructed=True,
    )
    if baseline_timeline is not None:
        plot_sm_util_timeline(
            baseline_timeline, baseline_ncu, axes[0][1],
            model_label=f"{baseline_label}  (pure-Transformer baseline)",
            is_reconstructed=True,
        )

    suptitle = (
        f"Reconstructed SM-utilisation timeline — seq_len={seq_len}  batch={batch_size}\n"
        f"Evidence for Problem 4/5: hybrid model layer-type SM-util heterogeneity\n"
        f"⚠ Reconstructed offline (nsys kernel timeline × ncu SM-util), not real-time."
    )
    fig.suptitle(suptitle, fontsize=10, y=1.02, ha="center")
    plt.tight_layout()
    fig.savefig(output_path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"  Figure: {output_path}")


