def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--results-dir", type=Path,
                   default=Path(_here) / "results" / "profiling")
    p.add_argument("--hybrid-model",   default="zamba2")
    p.add_argument("--baseline-model", default="llama3_8b",
                   help="Pure-Transformer baseline model (none = skip comparison panel)")
    p.add_argument("--seq-len",    type=int, default=2048)
    p.add_argument("--batch-size", type=int, default=1)
    p.add_argument("--output-dir", type=Path, default=None,
                   help="Where to save figures (default: --results-dir)")
    p.add_argument("--use-prior-sm-util", action="store_true",
                   help="Use built-in SM-util prior values even if ncu CSV exists")
    return p.parse_args()


def _load_model_data(
    results_dir: Path,
    model: str,
    seq_len: int,
    batch_size: int,
    use_prior: bool,
) -> tuple[Optional[pd.DataFrame], dict[str, float]]:
    """Load timeline CSV and ncu CSV for one model."""
    tag          = f"{model}_sl{seq_len}_bs{batch_size}"
    timeline_csv = results_dir / f"kernel_timeline_{tag}.csv"
    ncu_csv      = results_dir / f"ncu_{tag}.csv"

    timeline: Optional[pd.DataFrame] = None
    ncu_util: dict[str, float] = {}

    if timeline_csv.exists():
        timeline = load_timeline(timeline_csv)
        print(f"  Timeline: {timeline_csv}  ({len(timeline)} kernels)")
    else:
        print(f"  Timeline CSV not found: {timeline_csv}")
        print(f"  Run profile_layer_heterogeneity.py first.")

    if not use_prior and ncu_csv.exists():
        ncu_util = load_ncu_sm_util(ncu_csv)
        print(f"  ncu SM-util: {ncu_util}")
    else:
        ncu_util = dict(_SM_UTIL_PRIOR)
        print(f"  Using prior SM-util values: {ncu_util}")

    return timeline, ncu_util


def main() -> None:
    args      = parse_args()
    out_dir   = args.output_dir or args.results_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    tag = f"{args.hybrid_model}_sl{args.seq_len}_bs{args.batch_size}"

    print(f"\n  Hybrid model   : {args.hybrid_model}")
    print(f"  Baseline model : {args.baseline_model}")
    print(f"  Shape          : seq_len={args.seq_len}  batch={args.batch_size}")
    print(f"  Results dir    : {args.results_dir}")

    hybrid_tl, hybrid_ncu = _load_model_data(
        args.results_dir, args.hybrid_model,
        args.seq_len, args.batch_size, args.use_prior_sm_util,
    )
    if hybrid_tl is None:
        print("\n  No timeline data for hybrid model — using synthetic demo data.")
        # Generate synthetic demo timeline for visualization testing
        rng = np.random.default_rng(42)
        n   = 200
        starts   = np.cumsum(rng.exponential(1e6, n))
        durations = rng.exponential(5e5, n)
        classes   = rng.choice(
            ["ssm_scan", "attn", "gemm", "elementwise"],
            size=n, p=[0.45, 0.20, 0.25, 0.10],
        )
        hybrid_tl = pd.DataFrame({
            "kernel_name":  [f"kernel_{i}" for i in range(n)],
            "start_ns":     starts,
            "duration_ns":  durations,
            "layer_class":  classes,
        })
        print("  (Synthetic demo data — run profile_layer_heterogeneity.py for real results)")

    baseline_tl: Optional[pd.DataFrame] = None
    baseline_ncu: dict[str, float] = {}

    if args.baseline_model != "none":
        baseline_tl, baseline_ncu = _load_model_data(
            args.results_dir, args.baseline_model,
            args.seq_len, args.batch_size, args.use_prior_sm_util,
        )
        if baseline_tl is None:
            # Synthetic baseline (all attn/gemm)
            rng = np.random.default_rng(99)
            n   = 160
            starts    = np.cumsum(rng.exponential(1e6, n))
            durations = rng.exponential(6e5, n)
            classes   = rng.choice(["attn", "gemm"], size=n, p=[0.55, 0.45])
            baseline_tl = pd.DataFrame({
                "kernel_name": [f"kernel_{i}" for i in range(n)],
                "start_ns":    starts,
                "duration_ns": durations,
                "layer_class": classes,
            })
            print("  (Synthetic baseline demo data)")

    # Figure
    fig_path = out_dir / f"layer_heterogeneity_{tag}.png"
    make_figure(
        hybrid_timeline=hybrid_tl,
        hybrid_ncu=hybrid_ncu,
        hybrid_label=args.hybrid_model,
        baseline_timeline=baseline_tl,
        baseline_ncu=baseline_ncu,
        baseline_label=args.baseline_model if args.baseline_model != "none" else "",
        output_path=fig_path,
        seq_len=args.seq_len,
        batch_size=args.batch_size,
    )

    # Caption
    zone_stats = compute_zone_stats(hybrid_tl, hybrid_ncu)
    write_caption(
        out_dir / f"caption_{tag}.txt",
        hybrid_label=args.hybrid_model,
        baseline_label=args.baseline_model if args.baseline_model != "none" else None,
        zone_stats=zone_stats,
    )
