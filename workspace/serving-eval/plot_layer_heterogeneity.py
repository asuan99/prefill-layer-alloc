def write_caption(
    output_path: Path,
    hybrid_label: str,
    baseline_label: Optional[str],
    zone_stats: dict,
) -> None:
    ssm_util  = zone_stats.get("ssm_scan", {}).get("mean_sm_util", float("nan"))
    attn_util = zone_stats.get("attn",     {}).get("mean_sm_util", float("nan"))
    diff      = attn_util - ssm_util

    lines = [
        f"Figure: Reconstructed SM-utilisation timeline for {hybrid_label}.",
        "",
        "Method: kernel durations from nsys (--trace=cuda,nvtx, 'profile_run' NVTX range).",
        "SM-util per kernel class from ncu (sm__active_cycles_sum / sm__cycles_elapsed_sum).",
        "Reconstruction assigns each time bin the SM-util of the dominant kernel class.",
        "Dashed SM-util curve indicates reconstructed (offline) measurement;",
        "NOT a real-time hardware counter trace.",
        "",
        f"SSM-scan zone mean SM-util : {ssm_util:.0f} %",
        f"Attn zone mean SM-util     : {attn_util:.0f} %",
        f"SM-util gap (Attn − SSM)   : {diff:.0f} pp",
        "",
        "Evidence for Problem 4 (hybrid models have higher SM-util variance across layer types)",
        "and Problem 5 (SSM layers leave SMs partially idle during prefill).",
    ]
    if baseline_label:
        lines += [
            "",
            f"Right panel: pure-Transformer baseline ({baseline_label}).",
            "In a pure-Transformer model, all layers are Attn + GEMM → lower variance.",
        ]
    with open(output_path, "w") as f:
        f.write("\n".join(lines))
    print(f"  Caption: {output_path}")


